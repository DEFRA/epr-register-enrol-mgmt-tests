/**
 * RA-304 seed — a work item parked in the internal `awaiting-decision` state.
 *
 * WHY A RAW MONGO DOCUMENT AND NOT A UI JOURNEY.
 *
 * RA-304 hides `awaiting-decision` behind the "Duly made" label, which means
 * the interesting subject of the story is an item that IS in that state. Since
 * RA-410 there is no way to produce one through the product:
 *
 *   - `submit-for-decision` is declared `CallerInvocable: false`, so it is
 *     absent from `availableActions` AND the generic apply-action route refuses
 *     it (asserted by ra-346-submit-for-decision-gating.e2e.js);
 *   - a decision is a single `POST /work-items/re-accreditation/{id}/decision`
 *     that applies `assessment-in-progress -> awaiting-decision ->
 *     approved/rejected` server-side in one call, so the waypoint is entered
 *     and discharged inside one write and is never observable afterwards
 *     (asserted by ra-410-cta-lifecycle.e2e.js).
 *
 * So the state is reachable only for items parked there BEFORE RA-410 shipped
 * — real, historical data (management-fe's `decision/eligibility.js` still
 * accepts `awaiting-decision` as a decision entry state precisely to rescue
 * them). This seed reproduces exactly that: a legacy item stranded in the
 * waypoint, which is the only population RA-304's presentation rules can ever
 * apply to.
 *
 * Nothing in management-be changes for RA-304, so there is no backend seeder to
 * extend; the compose Mongo init script is the mechanism this suite already
 * uses to introduce a document no UI journey can create (see
 * 20-legacy-snapshot-work-item.js for the RA-342 precedent, including why it
 * has to run from inside the Mongo container and why it survives the backend's
 * idempotent startup seeding).
 *
 * CONSEQUENCE FOR THE SPECS: this script runs only in the docker-compose stack,
 * so the two RA-304 specs skip their seeded-item assertions when the item is
 * absent (a plain local stack) rather than faking a pass. The real coverage is
 * the CI compose run.
 *
 * The database name mirrors Mongo__DatabaseName in
 * docker/config/management-be.env and the collection name mirrors
 * WorkItemPersistence ("workItems"). A fixed _id makes the insert idempotent
 * across re-inits (replaceOne upsert).
 */

/* global db */

const caseManagementDb = db.getSiblingDB('epr-register-case-management')

const now = new Date()

const awaitingDecisionWorkItem = {
  // WorkItem.Id is a Guid stored as a String ([BsonRepresentation(String)]),
  // so _id must be a parseable GUID string.
  _id: '00000304-0000-4000-8000-000000000304',
  typeId: 're-accreditation',
  // The whole point of the fixture.
  stateId: 'awaiting-decision',
  submittedAt: now,
  lastModifiedAt: now,
  templateVersion: '1',
  version: 0,
  payload: {
    // The card's link text is payload.applicationReference (see decorate() in
    // the management-fe list controller); without one the link renders
    // zero-size and un-clickable.
    applicationReference: 'AP304AWAITING1',
    // Shares the RA304 prefix with nothing else in the suite, so an
    // organisation search resolves to exactly this item.
    organisationName: 'RA-304 Awaiting Decision Ltd',
    registrationNumber: 'EPR-304000',
    operatorRegistrationId: 'reg-304',
    material: 'plastic',
    previousAccreditationYear: 2025,
    complianceIssuesReported: 0,
    operatorEmail: 'ra304.awaiting@example.test',
    // Not generated by ApplicationReferenceGenerator (the reference above is
    // written directly), so this postcode consumes none of the 5 slots that
    // generator allows per (year, agency, org, postcode-suffix, material)
    // tuple and cannot collide with a spec-created item.
    siteAddressPostcode: 'SW1A 3DD',
    nation: 'England'
  },
  // A frozen snapshot is required for the backend to deserialise and project
  // the row. Deliberately minimal: `awaiting-decision` is a dead end for this
  // fixture, so it declares no transitions and the detail page projects no
  // actions — which is precisely what a stranded item looks like. The
  // user-visible status label does NOT come from here: management-fe resolves
  // it from its own module declaration (`re-accreditation/module.js` STATES),
  // which is the thing RA-304 changed, so the snapshot cannot mask a
  // regression in it.
  templateSnapshot: {
    templateVersion: '1',
    states: [
      {
        // WorkItemState.Id -> _id (NamedIdMemberConvention).
        _id: 'awaiting-decision',
        displayName: 'Awaiting decision',
        isTerminal: false
      },
      {
        _id: 'approved',
        displayName: 'Approved',
        isTerminal: true
      },
      {
        _id: 'rejected',
        displayName: 'Rejected',
        isTerminal: true
      }
    ],
    transitions: [],
    tasksByState: {}
  }
}

caseManagementDb.workItems.replaceOne(
  { _id: awaitingDecisionWorkItem._id },
  awaitingDecisionWorkItem,
  { upsert: true }
)

print(
  'RA-304: seeded awaiting-decision work item ' +
    awaitingDecisionWorkItem._id +
    ' into epr-register-case-management.workItems'
)
